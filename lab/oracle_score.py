#!/usr/bin/env python3
"""
Nature-Mirror Mesh -- Propagation Oracle: SCORE step.

Runs AFTER the simultaneous recordings exist. Decodes every recording
with ft8_lib (same method proven in .github/workflows/kiwisdr.yml:
slice into 15 s windows at a 2 s stride, run decode_ft8 per window,
collect unique messages), then scores the PRE-EXISTING prediction
(lab/results/oracle_prediction.json, generated by oracle_predict.py
before any recording) against the measurements.

Writes lab/results/oracle_ci.log:
  1. the prediction header, verbatim (oracle_prediction_header.txt)
  2. the record step's notes, verbatim (record_notes.txt, if present)
  3. per recording: host, band, WAV bytes, recorder log tail,
     total decode events, unique decode count, unique message list
  4. SCORECARD: per site "oracle predicted X better; measured:
     20m = N unique, 40m = M unique -> oracle CORRECT / WRONG / TIE",
     plus per-band predicted-category vs measured-category agreement
     and one overall line.

Honesty rules baked in:
  * Zero decodes is a result, reported as 0 -- never dressed up.
  * A missing recording is reported as MISSING (with the recorder
    log shown), and that site scores INDETERMINATE, never CORRECT.
  * If both bands measure 0 unique at a site, the verdict is
    INDETERMINATE (nothing was heard; the oracle's band preference
    could not be tested there).
  * Categories: none = 0, few = 1-9, many = >= 10 unique decodes
    (identical thresholds to oracle_predict.py).

Receive-only: this script only reads WAV files and runs a decoder.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import wave

import numpy as np

COMBOS = [
    ("ireland", "emeraldsdr.ddns.net:8073", "Carlow, Ireland (Europe)",
     [(14074, "20m"), (7074, "40m")]),
    ("australia", "22537.proxy.kiwisdr.com:8073",
     "Esk, Queensland, Australia (Oceania)",
     [(14074, "20m"), (7074, "40m")]),
]


def categorize(n):
    if n >= 10:
        return "many"
    if n >= 1:
        return "few"
    return "none"


def decode_wav(wav_path, decode_ft8, log):
    """Decode one WAV exactly like kiwisdr.yml. Returns (events, dict
    msg->first decode line)."""
    w = wave.open(wav_path, "rb")
    nch, sw, rate, n = (w.getnchannels(), w.getsampwidth(),
                        w.getframerate(), w.getnframes())
    raw = w.readframes(n)
    w.close()
    x = np.frombuffer(raw, dtype=np.int16)
    if nch > 1:
        x = x[::nch]
    x = x.astype(np.float64)
    log.append("WAV: %d Hz, %d channel(s), %d-bit, %.1f s, %d bytes"
               % (rate, nch, sw * 8, n / float(rate), len(raw)))
    if rate != 12000:
        m = int(round(len(x) * 12000.0 / rate))
        x = np.interp(np.arange(m) * rate / 12000.0,
                      np.arange(len(x)), x)
        log.append("Resampled %d -> 12000 Hz (decode_ft8 expects "
                   "12000 Hz mono)" % rate)
        rate = 12000
    x = np.clip(x, -32767, 32767).astype(np.int16)

    win = 15 * rate
    stride = 2 * rate
    total_events = 0
    unique = {}
    if len(x) >= win:
        starts = list(range(0, len(x) - win + 1, stride))[:60]
    else:
        starts = [0]
        log.append("WARNING: recording shorter than 15 s; decoding a "
                   "single zero-padded window.")
    log.append("Windows: %d x 15 s, stride 2 s (FT8 slots are 15 s, "
               "UTC-aligned; the 2 s stride guarantees a window starts "
               "within 2 s before every slot boundary)." % len(starts))
    for s in starts:
        seg = x[s:s + win]
        if len(seg) < win:
            seg = np.pad(seg, (0, win - len(seg)))
        fn = "/tmp/oracle_win.wav"
        wo = wave.open(fn, "wb")
        wo.setnchannels(1)
        wo.setsampwidth(2)
        wo.setframerate(rate)
        wo.writeframes(seg.tobytes())
        wo.close()
        p = subprocess.run([decode_ft8, fn], capture_output=True,
                           text=True)
        m = re.search(r"Decoded (\d+) messages", p.stderr)
        cnt = int(m.group(1)) if m else 0
        total_events += cnt
        lines = [ln for ln in p.stdout.splitlines() if "~" in ln]
        if lines:
            log.append("[window offset %3d s] %d message(s)"
                       % (s // rate, cnt))
            for ln in lines:
                log.append("    " + ln)
                msg = ln.split("~", 1)[1].strip()
                if msg and msg not in unique:
                    unique[msg] = ln
    return total_events, unique


def tail(path, n=15):
    try:
        with open(path, errors="replace") as f:
            lines = f.read().splitlines()
        return lines[-n:]
    except OSError:
        return ["(no recorder log found at %s)" % path]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rec-dir", default="/tmp/oracle_rec")
    ap.add_argument("--results-dir",
                    default=os.path.join(os.path.dirname(
                        os.path.abspath(__file__)), "results"))
    ap.add_argument("--decode-ft8", default=None,
                    help="path to ft8_lib decode_ft8 (default: "
                         "<project>/lab/ft8_lib/decode_ft8)")
    args = ap.parse_args()

    project_lab = os.path.dirname(os.path.abspath(__file__))
    decode_ft8 = args.decode_ft8 or os.path.join(
        project_lab, "ft8_lib", "decode_ft8")
    results_dir = args.results_dir
    pred_path = os.path.join(results_dir, "oracle_prediction.json")
    header_path = os.path.join(results_dir,
                               "oracle_prediction_header.txt")
    out_path = os.path.join(results_dir, "oracle_ci.log")

    log = []
    log.append("=== PROPAGATION ORACLE TEST -- RESULTS (GitHub Actions, "
               "zero-dollar, receive-only) ===")
    log.append("Method: oracle_predict.py FIRST (NOAA solar data + "
               "model), then 4 simultaneous kiwirecorder recordings "
               "(2 receivers x 2 bands, 90 s), then ft8_lib decode + "
               "this scorecard. Prediction precedes measurement; the "
               "score is computed from the committed prediction file.")

    # ---- prediction, verbatim header first ----
    pred = None
    if os.path.exists(header_path):
        log.append("")
        with open(header_path, errors="replace") as f:
            log.append(f.read().rstrip("\n"))
    else:
        log.append("")
        log.append("WARNING: oracle_prediction_header.txt NOT FOUND -- "
                   "no prediction header to reproduce.")
    if os.path.exists(pred_path):
        with open(pred_path) as f:
            pred = json.load(f)
    else:
        log.append("WARNING: oracle_prediction.json NOT FOUND -- "
                   "scorecard will be INDETERMINATE for every site.")

    # ---- record notes, verbatim ----
    notes = os.path.join(args.rec_dir, "record_notes.txt")
    if os.path.exists(notes):
        log.append("")
        log.append("--- Record step notes (verbatim) ---")
        with open(notes, errors="replace") as f:
            log.append(f.read().rstrip("\n"))

    # ---- decode every recording ----
    measured = {}   # site -> band -> (events, unique dict) or None
    log.append("")
    log.append("=== MEASUREMENTS ===")
    for site, host, label, bands in COMBOS:
        measured[site] = {}
        for freq, band in bands:
            tag = "rec_%s_%d" % (site, freq)
            wav_path = os.path.join(args.rec_dir, tag + ".wav")
            log.append("")
            log.append("--- Recording: site=%s host=%s (%s) band=%s "
                       "freq=%d kHz USB ---" % (site, host, label,
                                                band, freq))
            reclog = os.path.join(args.rec_dir, tag + ".recorder.log")
            log.append("Recorder log (tail):")
            for ln in tail(reclog):
                log.append("    " + ln)
            if not os.path.exists(wav_path):
                log.append("RECORDING MISSING: no WAV at %s. This "
                           "combination produced no recording (see "
                           "recorder log + record notes); it is scored "
                           "as missing, NOT as zero decodes."
                           % wav_path)
                measured[site][band] = None
                continue
            size = os.path.getsize(wav_path)
            log.append("WAV bytes: %d" % size)
            if size < 20000:
                log.append("WAV is suspiciously small (%d bytes); "
                           "decoding attempted anyway." % size)
            try:
                events, unique = decode_wav(wav_path, decode_ft8, log)
            except Exception as e:  # noqa: BLE001 - log, don't crash
                log.append("DECODE ERROR for %s: %s: %s"
                           % (wav_path, type(e).__name__, e))
                measured[site][band] = None
                continue
            log.append("Total decode events (incl. duplicates across "
                       "overlapping windows): %d" % events)
            log.append("Unique FT8 messages decoded: %d" % len(unique))
            for msg, ln in unique.items():
                log.append("  " + ln)
            if not unique:
                log.append("Zero decodes from this recording -- "
                           "reported as measured: none.")
            measured[site][band] = (events, unique)

    # ---- scorecard ----
    log.append("")
    log.append("=== SCORECARD ===")
    pred_sites = {}
    if pred:
        for s in pred.get("sites", []):
            pred_sites[s["site"]] = s
    verdicts = []
    for site, host, label, bands in COMBOS:
        ps = pred_sites.get(site)
        m = measured.get(site, {})
        counts = {}
        missing = False
        for _freq, band in bands:
            v = m.get(band)
            if v is None:
                missing = True
                counts[band] = None
            else:
                counts[band] = len(v[1])
        log.append("")
        log.append("Site %s (%s):" % (site, label))
        if ps is None:
            log.append("  No prediction found for this site -> "
                       "INDETERMINATE.")
            verdicts.append("INDETERMINATE")
            continue
        predicted_best = ps.get("predicted_best_band")
        other = "40m" if predicted_best == "20m" else "20m"
        log.append("  Oracle predicted: %s better (20m expected %s, "
                   "40m expected %s)"
                   % (predicted_best,
                      ps["bands"]["20m"]["expected_decodes"],
                      ps["bands"]["40m"]["expected_decodes"]))
        if missing:
            log.append("  Measured: 20m = %s unique, 40m = %s unique "
                       "(a recording is missing)"
                       % (counts["20m"], counts["40m"]))
            log.append("  Verdict: INDETERMINATE -- missing recording "
                       "cannot test the prediction.")
            verdicts.append("INDETERMINATE")
            continue
        log.append("  Measured: 20m = %d unique, 40m = %d unique"
                   % (counts["20m"], counts["40m"]))
        if counts["20m"] == 0 and counts["40m"] == 0:
            verdict = ("INDETERMINATE (both bands silent -- nothing "
                       "heard, band preference untestable)")
            verdicts.append("INDETERMINATE")
        elif counts[predicted_best] > counts[other]:
            verdict = "CORRECT"
            verdicts.append("CORRECT")
        elif counts[predicted_best] < counts[other]:
            verdict = "WRONG"
            verdicts.append("WRONG")
        else:
            verdict = "TIE (equal unique decodes on both bands)"
            verdicts.append("TIE")
        log.append("  Verdict: oracle %s" % verdict)
        for _freq, band in bands:
            pred_cat = ps["bands"][band]["expected_decodes"]
            meas_cat = categorize(counts[band])
            log.append("  Band %s: predicted %s, measured %d unique "
                       "(%s) -> %s"
                       % (band, pred_cat, counts[band], meas_cat,
                          "category MATCH" if pred_cat == meas_cat
                          else "category MISS"))
    log.append("")
    log.append("OVERALL: sites CORRECT=%d WRONG=%d TIE=%d "
               "INDETERMINATE=%d of %d"
               % (verdicts.count("CORRECT"), verdicts.count("WRONG"),
                  verdicts.count("TIE"),
                  verdicts.count("INDETERMINATE"), len(COMBOS)))
    log.append("NOTE: decode_ft8 prints a placeholder 000000 time "
               "field for file input; a decode's approximate UTC = "
               "recording start + window offset + DT column.")
    log.append("No radio transmission of any kind was made by this "
               "test; it only received public receivers' audio over "
               "the internet and decoded it.")

    os.makedirs(results_dir, exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(log) + "\n")
    print("\n".join(log))
    print("\nWrote %s" % out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
